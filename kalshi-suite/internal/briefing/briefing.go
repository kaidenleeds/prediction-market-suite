// Package briefing renders a Markdown market briefing from the app's LIVE Kalshi
// data (the same future-closing markets the dashboard shows). Generating it inside
// the running app is what keeps it fresh — the old external scheduled task kept
// pulling a stale, already-resolved snapshot.
package briefing

import (
	"context"
	"fmt"
	"sort"
	"strings"
	"time"

	"github.com/kalshi-suite/kalshi-suite/internal/ev"
	"github.com/kalshi-suite/kalshi-suite/internal/kalshi"
	"github.com/kalshi-suite/kalshi-suite/internal/signal"
)

// Generate builds the briefing markdown for the current moment.
func Generate(ctx context.Context, kal *kalshi.Client, now time.Time) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Kalshi Briefing — %s\n\n", now.Format("Mon Jan 2, 3:04 PM MST"))

	markets, err := kal.GetTopLiquidMarkets(ctx)
	if err != nil {
		fmt.Fprintf(&b, "Could not fetch live markets: %v\n", err)
		return b.String()
	}
	if len(markets) == 0 {
		b.WriteString("No open markets in the pull window (~18 days) right now.\n")
		return b.String()
	}

	// Surface real signals across the live board: positive cross-side arb (after
	// fees) and sharp recent moves.
	type sig struct {
		title string
		note  string
		score float64
	}
	var signals []sig
	for _, m := range markets {
		title := marketName(m)
		if arb := signal.ArbProfit(ev.General, m.YesAsk.Float(), m.NoAsk.Float()); arb > 0 {
			signals = append(signals, sig{title,
				fmt.Sprintf("ARB +%.0f¢ (YES %.0f¢ + NO %.0f¢ < $1)", arb*100, m.YesAsk.Float()*100, m.NoAsk.Float()*100),
				1000 + arb})
			continue
		}
		mv := signal.MoveCents(m.LastPrice.Float(), m.PreviousPrice.Float())
		if mv >= 4 {
			signals = append(signals, sig{title, fmt.Sprintf("▲ moved +%.0f¢ (now %.0f%%)", mv, m.ImpliedProbability()*100), mv})
		} else if mv <= -4 {
			signals = append(signals, sig{title, fmt.Sprintf("▼ moved %.0f¢ (now %.0f%%)", mv, m.ImpliedProbability()*100), -mv})
		}
	}
	sort.Slice(signals, func(i, j int) bool { return signals[i].score > signals[j].score })

	fmt.Fprintf(&b, "**%d** open markets in the pull window (~18 days; R73 full universe).\n\n", len(markets))

	if len(signals) == 0 {
		b.WriteString("**Read: no clear edge after fees right now — holding.** Nothing on the live board shows a positive cross-side arb or a sharp move.\n\n")
	} else {
		b.WriteString("**Signals worth a look** (screen only — confirm price + fees before acting):\n\n")
		for i, s := range signals {
			if i >= 8 {
				break
			}
			fmt.Fprintf(&b, "- %s — %s\n", s.title, s.note)
		}
		b.WriteString("\n")
	}

	b.WriteString("## Most active (by 24h volume)\n\n")
	b.WriteString("| Market | Chance | 24h Vol | Resolves |\n|---|---|---|---|\n")
	for i, m := range markets {
		if i >= 15 {
			break
		}
		when := m.ExpectedExpiration
		if when == "" {
			when = m.CloseTime
		}
		if t, e := time.Parse(time.RFC3339, when); e == nil {
			when = t.Local().Format("Jan 2 3:04 PM")
		}
		fmt.Fprintf(&b, "| %s | %.0f%% | %s | %s |\n",
			clip(marketName(m), 48), m.ImpliedProbability()*100, humanVol(m.Volume24h.Float()), when)
	}
	b.WriteString("\n_Paper mode — no real orders. Generated by the suite from live data._\n")
	return b.String()
}

func marketName(m kalshi.Market) string {
	if m.YesSubTitle != "" {
		return m.Title + " — " + m.YesSubTitle
	}
	return m.Title
}

func humanVol(v float64) string {
	switch {
	case v >= 1e6:
		return fmt.Sprintf("%.1fM", v/1e6)
	case v >= 1e3:
		return fmt.Sprintf("%.1fk", v/1e3)
	default:
		return fmt.Sprintf("%.0f", v)
	}
}

func clip(s string, n int) string {
	r := []rune(s)
	if len(r) <= n {
		return s
	}
	return string(r[:n-1]) + "…"
}
